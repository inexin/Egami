"""Translates libvpx 1.14.1's one-dimensional VP9 forward transforms (vp9/encoder/vp9_dct.c and vpx_dsp/fwd_txfm.c, BSD-3; see
THIRD-PARTY-NOTICES) into C#, line by line, from .cache/libvpx-1.14.1 (python tools/video/make-vp9-tables.py clones it).

  src/Egami.Video/Codecs/Vp9/Vp9Transform.Forward.OneD.cs
      fdct4, fadst4, fdct8, fadst8, fdct16 and fadst16 (32-bit values, 64-bit products, as libvpx's high bit depth build holds
      them) and vpx_fdct32 (64-bit throughout). The two-dimensional passes around them are written by hand in
      Vp9Transform.Forward.cs, after vp9_fht4x4_c, vp9_fht8x8_c, vp9_fht16x16_c and vpx_fdct32x32_c / _rd_c.

  src/Egami.Video/Codecs/Vp9/Vp9TransformSimd.Forward.OneD.cs
      the same transforms on vectors of 32-bit lanes (Vector128 for the 4-point ones, Vector256 for all), one column per lane,
      for 8-bit residuals, whose intermediates and products fit 32 bits (the 32-point one with the rd variant's mid-way
      rounding on the row pass).

Usage, from the repo root: python tools/video/make-vp9-forward-transforms.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
VPX = os.path.join(ROOT, ".cache", "libvpx-1.14.1")
OUT = os.path.join(ROOT, "src", "Egami.Video", "Codecs", "Vp9", "Vp9Transform.Forward.OneD.cs")
SIMD_OUT = os.path.join(ROOT, "src", "Egami.Video", "Codecs", "Vp9", "Vp9TransformSimd.Forward.OneD.cs")

FUNCTIONS = [
    ("vp9/encoder/vp9_dct.c", "fdct4", "Fdct4", "int"),
    ("vp9/encoder/vp9_dct.c", "fadst4", "Fadst4", "int"),
    ("vp9/encoder/vp9_dct.c", "fdct8", "Fdct8", "int"),
    ("vp9/encoder/vp9_dct.c", "fadst8", "Fadst8", "int"),
    ("vp9/encoder/vp9_dct.c", "fdct16", "Fdct16", "int"),
    ("vp9/encoder/vp9_dct.c", "fadst16", "Fadst16", "int"),
    ("vpx_dsp/fwd_txfm.c", "vpx_fdct32", "Fdct32", "long"),
]


def body_of(text, name):
    match = re.search(r"^(?:static )?void " + name + r"\(([^)]*)\) \{", text, flags=re.M)
    start = match.end()
    depth = 1
    i = start
    while depth:
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    return text[start:i - 1]


def translate(body, element):
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    # fdct16 names its arguments in and out, which are C# keywords.
    body = re.sub(r"\bin\[", "src[", body)
    body = re.sub(r"\bout\[", "output[", body)
    body = body.replace("fdct_round_shift(", "Rs(").replace("dct_32_round(", "Rs(").replace("half_round_shift(", "Hrs(")
    body = body.replace("(tran_high_t)", "(long)").replace("(tran_low_t)", "(" + element + ")")
    body = re.sub(r"cospi_(\d+)_64", r"C\1", body)
    body = re.sub(r"sinpi_(\d)_9", r"S\1", body)
    body = re.sub(r"if \(!\(([^;{]*?)\)\) \{", r"if ((\1) == 0) {", body, flags=re.S)
    body = re.sub(r"if \(round\) \{", r"if (round) {", body)
    body = re.sub(r"tran_high_t (\w+)\[(\d+)\];", r"Span<long> \1 = stackalloc long[\2];", body)
    body = re.sub(r"tran_low_t (\w+)\[(\d+)\];", r"Span<int> \1 = stackalloc int[\2];", body)
    body = body.replace("tran_high_t ", "long ").replace("tran_low_t ", "int ")
    body = re.sub(r"=\s*\n\s+", "= ", body)
    body = re.sub(r"([-+*|])\s*\n\s+", r"\1 ", body)
    body = re.sub(r"\n(\s*\n)+", "\n\n", body)
    lines = []
    for line in body.strip("\n").split("\n"):
        stripped = line.strip()
        if not stripped:
            if lines and lines[-1] != "" and not lines[-1].endswith("{"):
                lines.append("")
            continue
        indent = "    " * (((len(line) - len(line.lstrip(" "))) // 2) + 1)
        if stripped.endswith("{"):
            if stripped != "{":
                lines.append(indent + stripped[:-1].rstrip())
            lines.append(indent + "{")
        else:
            lines.append(indent + stripped)
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines)


HEADER = """// <auto-generated>
// Generated by tools/video/make-vp9-forward-transforms.py from libvpx 1.14.1 (BSD-3, Google patent grant; see THIRD-PARTY-NOTICES).
// Do not edit; run the script again.
// </auto-generated>
#nullable enable
"""


def vectorize(code, vector):
    """The scalar C# of one transform on vectors: every int and long becomes the vector type, the casts go."""
    code = code.replace("(long)", "").replace("(int)", "")
    code = re.sub(r"\blong (\w)", vector + r" \1", code)
    code = re.sub(r"\bint (\w)", vector + r" \1", code)
    code = code.replace("Span<int>", f"Span<{vector}>").replace("stackalloc int[", f"stackalloc {vector}[")
    code = code.replace("Span<long>", f"Span<{vector}>").replace("stackalloc long[", f"stackalloc {vector}[")
    code = re.sub(r"if \((\(.*?\)) == 0\)", lambda m: f"if ({m.group(1)} == {vector}.Zero)", code)
    code = code.replace("output[0] = output[1] = output[2] = output[3] = 0;", f"output[0] = output[1] = output[2] = output[3] = {vector}.Zero;")
    return code


def main():
    out = [HEADER, "namespace Egami.Video.Codecs.Vp9;", "",
           "/// <summary>libvpx's one-dimensional forward transforms, translated line by line.</summary>",
           "internal static partial class Vp9Transform", "{"]
    for path, c_name, cs_name, element in FUNCTIONS:
        text = open(os.path.join(VPX, path)).read()
        input_name = "src" if c_name == "fdct16" else "input"
        out.append(f"    /// <summary>libvpx's {c_name}.</summary>")
        extra = ", bool round" if c_name == "vpx_fdct32" else ""
        out.append(f"    internal static void {cs_name}(ReadOnlySpan<{element}> {input_name}, Span<{element}> output{extra})")
        out.append("    {")
        out.append(translate(body_of(text, c_name), element))
        out.append("    }")
        out.append("")
    out[-1] = "}"
    open(OUT, "w", newline="\n").write("\n".join(out) + "\n")
    print(f"{len(FUNCTIONS)} transforms written to {os.path.relpath(OUT, ROOT)}")

    simd = [HEADER, "using System.Runtime.Intrinsics;", "", "namespace Egami.Video.Codecs.Vp9;", "",
            "/// <summary>libvpx's one-dimensional forward transforms on vectors, one column per lane (8-bit residuals only).</summary>",
            "internal static partial class Vp9TransformSimd", "{"]
    count = 0
    for vector in ("Vector128<int>", "Vector256<int>"):
        for path, c_name, cs_name, element in FUNCTIONS:
            if vector == "Vector128<int>" and c_name not in ("fdct4", "fadst4"):
                continue
            text = open(os.path.join(VPX, path)).read()
            input_name = "src" if c_name == "fdct16" else "input"
            extra = ", bool round" if c_name == "vpx_fdct32" else ""
            simd.append(f"    /// <summary>libvpx's {c_name}, a column per lane.</summary>")
            simd.append(f"    internal static void {cs_name}(ReadOnlySpan<{vector}> {input_name}, Span<{vector}> output{extra})")
            simd.append("    {")
            simd.append(vectorize(translate(body_of(text, c_name), element), vector))
            simd.append("    }")
            simd.append("")
            count += 1
    simd[-1] = "}"
    open(SIMD_OUT, "w", newline="\n").write("\n".join(simd) + "\n")
    print(f"{count} vector transforms written to {os.path.relpath(SIMD_OUT, ROOT)}")


if __name__ == "__main__":
    main()
