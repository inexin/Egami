"""Generates the tables of the Opus encoder's tonality analysis from libopus 1.5.2's sources (BSD-3; see THIRD-PARTY-NOTICES):

  src/Egami.Video/Audio/Codecs/Opus/OpusAnalysisTables.Data.cs   the DCT table, analysis window and band edges of src/analysis.c
                                                                 and the weights of the speech/music network in src/mlp_data.c.

Usage, from the repo root: python tools/video/make-opus-analysis-tables.py [path to the libopus 1.5.2 checkout]
(default .cache/audio/opus: git clone --depth 1 --branch v1.5.2 https://github.com/xiph/opus .cache/audio/opus).
"""
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OPUS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, ".cache", "audio", "opus")
OUT = os.path.join(ROOT, "src", "Egami.Video", "Audio", "Codecs", "Opus", "OpusAnalysisTables.Data.cs")

_spec = importlib.util.spec_from_file_location("celt_tables", os.path.join(os.path.dirname(os.path.abspath(__file__)), "make-celt-tables.py"))
celt = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(celt)

# (C# name, file, libopus name, C# element type)
TABLES = [
    ("DctTable", "src/analysis.c", "dct_table", "float"),
    ("AnalysisWindow", "src/analysis.c", "analysis_window", "float"),
    ("TBands", "src/analysis.c", "tbands", "short"),
    ("Layer0Weights", "src/mlp_data.c", "layer0_weights", "sbyte"),
    ("Layer0Bias", "src/mlp_data.c", "layer0_bias", "sbyte"),
    ("Layer1Weights", "src/mlp_data.c", "layer1_weights", "sbyte"),
    ("Layer1RecurWeights", "src/mlp_data.c", "layer1_recur_weights", "sbyte"),
    ("Layer1Bias", "src/mlp_data.c", "layer1_bias", "sbyte"),
    ("Layer2Weights", "src/mlp_data.c", "layer2_weights", "sbyte"),
    ("Layer2Bias", "src/mlp_data.c", "layer2_bias", "sbyte"),
]

HEADER = """// <auto-generated>
// Generated by tools/video/make-opus-analysis-tables.py from libopus 1.5.2 (BSD-3; see THIRD-PARTY-NOTICES).
// Do not edit; run the script again.
// </auto-generated>
#nullable enable

namespace Egami.Video.Audio.Codecs.Opus;

/// <summary>Numeric tables of libopus's tonality analysis and its speech/music network, flattened in array order.</summary>
internal static partial class OpusAnalysisTables
{
"""


def main():
    cache = {}
    parts = []
    for cs_name, file, c_name, kind in TABLES:
        if file not in cache:
            with open(os.path.join(OPUS, file)) as f:
                cache[file] = celt.strip_comments(celt.preprocess(f.read()))
        items = celt.values(celt.initializer(cache[file], c_name), kind)
        parts.append(f"    /// <summary>libopus's {c_name}[{len(items)}] ({file}).</summary>\n"
                     f"    internal static ReadOnlySpan<{kind}> {cs_name} =>\n    [\n{celt.wrap(items, '        ')}\n    ];\n")
    with open(OUT, "w", newline="\n") as f:
        f.write(HEADER + "\n".join(parts) + "}\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
