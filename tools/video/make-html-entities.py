"""Writes src/Egami.Video/Subtitles/HtmlEntities.Data.cs: the HTML named character references, which WebVTT cue text uses.

The table comes from Python's html.entities.html5, a copy of the WHATWG HTML list (https://html.spec.whatwg.org/entities.json).
Names without a trailing ';' are the legacy references HTML also accepts without one.

Usage: python tools/video/make-html-entities.py   (from the repo root)
"""
import html.entities

OUT = "src/Egami.Video/Subtitles/HtmlEntities.Data.cs"


def escape(text):
    return "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else "\\u%04X" % ord(c) if ord(c) < 0x10000 else
                   "".join("\\u%04X" % u for u in surrogates(ord(c))) for c in text)


def surrogates(code):
    code -= 0x10000
    return (0xD800 + (code >> 10), 0xDC00 + (code & 0x3FF))


entries = sorted(html.entities.html5.items())
lines = ["// <auto-generated>Made by tools/video/make-html-entities.py from the WHATWG HTML named character references. Do not edit.</auto-generated>",
         "namespace Egami.Video.Subtitles;", "", "internal static partial class HtmlEntities", "{",
         "    // name, tab, value, newline; names with ';' and the legacy ones without.", "    private const string Table ="]
chunk = []
for name, value in entries:
    chunk.append(f"{name}\\t{escape(value)}\\n")
    if len(chunk) == 8:
        lines.append('        "' + "".join(chunk) + '" +')
        chunk = []
lines.append('        "' + "".join(chunk) + '";')
lines.append("}")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"{len(entries)} entities")
