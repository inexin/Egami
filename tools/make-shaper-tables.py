"""Generates the script shapers' tables from HarfBuzz 14.5.1 (MIT) for Egami.Fonts.Shaping (2.8.1 tasks 9 to 11).

HarfBuzz's script shapers rest on generated data: the Arabic presentation-form tables its fallback shaping synthesizes GSUB from,
the vowel constraints that insert dotted circles, the scripts sent to the Universal Shaping Engine and its categories, and the
Ragel syllable machines of the Indic, Khmer, Myanmar and USE shapers. Egami translates that data so its shapers make the same
decisions as hb-shape.
The tool reads the sources from HarfBuzz 14.5.1's release tarball (SHA-256 checked, downloaded into .cache/shaping by
tools/make-shaping-references.py) and writes:

  src/Egami.Fonts/Shaping/ArabicTables.g.cs       presentation forms and the fallback ligatures
  src/Egami.Fonts/Shaping/VowelConstraints.g.cs   dotted circles between vowels that look like another vowel
  src/Egami.Fonts/Shaping/ShaperScripts.g.cs      the scripts HarfBuzz sends to the Universal Shaping Engine
  src/Egami.Fonts/Shaping/SyllableMachines.g.cs   the Indic, Khmer and Myanmar syllable machines
  src/Egami.Fonts/Shaping/UseTable.g.cs           the Universal Shaping Engine categories
  src/Egami.Fonts/Shaping/UseMachine.g.cs         the Universal Shaping Engine syllable machine
  src/Egami.Fonts/Shaping/IndicTables.g.cs        the Indic, Khmer and Myanmar categories and Indic positions

Usage, from the repo root:
  python tools/make-shaper-tables.py
"""
import hashlib
import io
import re
import sys
import tarfile

VERSION = "14.5.1"
TARBALL = f".cache/shaping/github.com_harfbuzz_harfbuzz_releases_download_{VERSION}_harfbuzz-{VERSION}.tar.xz"
SHA256 = "7e2fa4e8c7c98e8d8140671f5772542afaaa6acccfbd746506886b6d85f7f8d6"
OUT = "src/Egami.Fonts/Shaping/"

data = open(TARBALL, "rb").read()
if hashlib.sha256(data).hexdigest() != SHA256:
    sys.exit(f"{TARBALL} does not match the pinned SHA-256; run tools/make-shaping-references.py first.")
archive = tarfile.open(fileobj=io.BytesIO(data))


def source(name):
    return archive.extractfile(f"harfbuzz-{VERSION}/src/{name}").read().decode("utf-8")


def header(what):
    return (
        "// <auto-generated/>\n"
        f"// Generated by tools/make-shaper-tables.py from HarfBuzz {VERSION}'s {what} (MIT); see THIRD-PARTY-NOTICES.md.\n"
        "// Do not edit.\n"
        "#pragma warning disable\n\n"
        "namespace Egami.Fonts.Shaping;\n\n"
    )


def write(name, text):
    with open(OUT + name, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


# Script names: HB_SCRIPT_DEVANAGARI -> "Deva".
script_codes = {}
for m in re.finditer(r"(HB_SCRIPT_[A-Z0-9_]+)\s*=\s*HB_TAG \('(.)','(.)','(.)','(.)'\)", source("hb-script-list.h")):
    script_codes[m.group(1)] = "".join(m.group(i) for i in range(2, 6))
script_codes["HB_SCRIPT_MYANMAR_ZAWGYI"] = "Qaag"


def array_body(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\[\d*\][^=]*=\s*\{", text)
    start = m.end()
    depth = 1
    i = start
    while depth:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
        i += 1
    return text[start:i - 1]


def numbers(text):
    return [int(n, 0) for n in re.findall(r"-?(?:0x[0-9A-Fa-f]+|\d+)", re.sub(r"/\*.*?\*/", "", text, flags=re.S))]


# ---- Arabic ----

PUA_LOOKUPS = """    private static int PuaB4(int offset, int i) => (PuaU8[offset + (i >> 1)] >> ((i & 1) << 2)) & 15;

    /// <summary>A Unicode Arabic character's private use code point in a Simplified Arabic (Windows 3.1 font page) font, or 0.</summary>
    public static int SimplifiedArabicPua(int u)
    {
        if ((uint)u >= 65277u)
        {
            return 0;
        }

        int a = PuaB4(0, ((int)((13835058055282164225UL >> ((u >> 11) << 1)) & 3) << 4) + ((u >> 7) & 15));
        int b = PuaU8[31 + (a << 4) + ((u >> 3) & 15)];
        return PuaU16[(b << 3) + (u & 7)];
    }

    /// <summary>A Unicode Arabic character's private use code point in a Traditional Arabic (Windows 3.1 font page) font, or 0.</summary>
    public static int TraditionalArabicPua(int u)
    {
        if ((uint)u >= 65277u)
        {
            return 0;
        }

        int a = PuaB4(127, u >> 10);
        int b = PuaB4(159, (a << 4) + ((u >> 6) & 15));
        int c = PuaU8[197 + (b << 4) + ((u >> 2) & 15)];
        return PuaU16[317 + (c << 2) + (u & 3)];
    }
"""

arabic = source("hb-ot-shaper-arabic-table.hh")
first = int(re.search(r"#define SHAPING_TABLE_FIRST\s+(0x[0-9A-Fa-f]+)u", arabic).group(1), 16)
last = int(re.search(r"#define SHAPING_TABLE_LAST\s+(0x[0-9A-Fa-f]+)u", arabic).group(1), 16)
shaping = numbers(re.sub(r"0x([0-9A-Fa-f]+)u", r"0x\1", array_body(arabic, "shaping_table")))
assert len(shaping) == (last - first + 1) * 4


def ligature_rows(name):
    body = re.sub(r"0x([0-9A-Fa-f]+)u", r"0x\1", array_body(arabic, name))
    rows = []
    for m in re.finditer(r"\{\s*(0x[0-9A-Fa-f]+),\s*\{(.*?)\}\},", body, re.S):
        ligs = []
        for lm in re.finditer(r"\{\s*\{([^}]*)\},\s*(0x[0-9A-Fa-f]+)\s*\}", m.group(2)):
            ligs.append(([int(c, 16) for c in re.findall(r"0x[0-9A-Fa-f]+", lm.group(1))], int(lm.group(2), 16)))
        rows.append((int(m.group(1), 16), ligs))
    return rows


def ligature_cs(name, cs_name):
    lines = [f"    /// <summary>HarfBuzz's {name}: first character, then each ligature's other components and the ligature.</summary>",
             f"    public static readonly (ushort First, (ushort[] Components, ushort Ligature)[] Ligatures)[] {cs_name} =", "    ["]
    for first_u, ligs in ligature_rows(name):
        items = ", ".join(f"([{', '.join(f'0x{c:04X}' for c in comps)}], 0x{lig:04X})" for comps, lig in ligs)
        lines.append(f"        (0x{first_u:04X}, [{items}]),")
    lines.append("    ];")
    return "\n".join(lines)


win = source("hb-ot-shaper-arabic-win1256.hh")


def glyphs(text):
    return [int(g) for g in re.findall(r"G\((\d+)\)", text)]


def single(name):
    m = re.search(r"OT_SUBLOOKUP_SINGLE_SUBST_FORMAT2\(" + name + r",(.*?)\n\)", win, re.S)
    body = m.group(1)
    parts = body.split(",\n")
    left = glyphs(parts[0])
    right = glyphs(parts[1])
    assert len(left) == len(right)
    return left, right


def ligature_set(name):
    return [(glyphs(m.group(1)), glyphs(m.group(2))[0]) for m in
            re.finditer(r"OT_LIGATURE\(" + name + r"Ligature\d+, (G\(\d+\)), (G\(\d+\))\)", win)]


win_cs = []
for sub in ["initmediSubLookup", "initSubLookup", "mediSubLookup", "finaSubLookup", "medifinaLamAlefSubLookup"]:
    left, right = single(sub)
    win_cs.append(f"    public static readonly (ushort[] From, ushort[] To) Win1256{sub[0].upper() + sub[1:]} = "
                  f"([{', '.join(map(str, left))}], [{', '.join(map(str, right))}]);")
for name, first_glyph in [("lamInit", 225), ("shadda", 248)]:
    ligs = ", ".join(f"({c[0]}, {g})" for c, g in ligature_set(name))
    win_cs.append(f"    public static readonly (ushort First, (ushort Component, ushort Ligature)[] Ligatures) Win1256{name[0].upper() + name[1:]}Ligatures = "
                  f"({first_glyph}, [{ligs}]);")

text = header("hb-ot-shaper-arabic-table.hh and hb-ot-shaper-arabic-win1256.hh")
text += "internal static class ArabicTables\n{\n"
text += f"    public const int ShapingTableFirst = 0x{first:04X};\n    public const int ShapingTableLast = 0x{last:04X};\n\n"
text += "    /// <summary>Each character's initial, medial, final and isolated presentation form, or 0.</summary>\n"
text += "    public static ReadOnlySpan<ushort> ShapingTable =>\n    [\n"
for i in range(0, len(shaping), 4):
    text += "        " + ", ".join(f"0x{v:04X}" for v in shaping[i:i + 4]) + ",\n"
text += "    ];\n\n"
text += ligature_cs("ligature_table", "Ligatures") + "\n\n"
text += ligature_cs("ligature_mark_table", "MarkLigatures") + "\n\n"
text += ligature_cs("ligature_3_table", "Ligatures3") + "\n\n"
text += "    // The hand-coded GSUB lookups for fonts laid out in Windows-1256 order (glyph ids).\n"
text += "\n".join(win_cs) + "\n\n"

pua = source("hb-ot-shaper-arabic-pua.hh")
for array, cs_name, cs_type in [("_hb_arabic_pua_u8", "PuaU8", "byte"), ("_hb_arabic_pua_u16", "PuaU16", "ushort")]:
    values = numbers(array_body(pua, array))
    text += f"    private static readonly {cs_type}[] {cs_name} =\n    [\n"
    for i in range(0, len(values), 24):
        text += "        " + ", ".join(map(str, values[i:i + 24])) + ",\n"
    text += "    ];\n\n"
# The two lookups into hb-ot-shaper-arabic-pua.hh's packed tables are written out; check the constants they rely on.
for expected in ["u<65277u", "13835058055282164225ULL", "_hb_arabic_pua_u8[31u+", "_hb_arabic_pua_u16[317u+",
                 "_hb_arabic_pua_u8+127u", "_hb_arabic_pua_u8+159u", "_hb_arabic_pua_u8[197u+"]:
    assert expected in pua, expected
text += PUA_LOOKUPS + "}\n"
write("ArabicTables.g.cs", text)

# ---- Vowel constraints ----

vowel = source("hb-ot-shaper-vowel-constraints.cc")
body = vowel[vowel.index("  switch ((unsigned) buffer->props.script)"):vowel.index("  buffer->sync ();")]
body = body.replace("switch ((unsigned) buffer->props.script)", "switch (script)")
body = re.sub(r"case (HB_SCRIPT_[A-Z0-9_]+):", lambda m: f'case "{script_codes[m.group(1)]}":', body)
body = body.replace("(void) buffer->next_glyph ();", "buffer.NextGlyph();")
body = body.replace("buffer->cur ()", "buffer.Cur()").replace("buffer->cur (1)", "buffer.Cur(1)").replace("buffer->cur (2)", "buffer.Cur(2)")
body = body.replace(".codepoint", ".Codepoint").replace("buffer->idx", "buffer.Idx").replace("buffer->successful", "buffer.Successful")
body = body.replace("_output_with_dotted_circle (buffer);", "OutputWithDottedCircle(buffer);")
body = body.replace("unsigned int count", "int count")
body = body.replace("\t", "        ")
assert "->" not in body, body
text = header("hb-ot-shaper-vowel-constraints.cc")
text += """internal static class VowelConstraints
{
    private static void OutputDottedCircle(LayoutBuffer buffer)
    {
        buffer.OutputGlyph(0x25CCu);
        UnicodeProps.ClearContinuation(ref buffer.Prev());
    }

    private static void OutputWithDottedCircle(LayoutBuffer buffer)
    {
        OutputDottedCircle(buffer);
        buffer.NextGlyph();
    }

    /// <summary>Inserts dotted circles between vowel sequences that look like another vowel, as the USE script development spec says.</summary>
    public static void Preprocess(LayoutBuffer buffer, string script)
    {
        if (buffer.DoNotInsertDottedCircle)
        {
            return;
        }

        buffer.ClearOutput();
        int count = buffer.Len;
"""
text += "\n".join("    " + line if line.strip() else "" for line in body.rstrip().split("\n")) + "\n"
text += "        buffer.Sync();\n    }\n}\n"
write("VowelConstraints.g.cs", text)

