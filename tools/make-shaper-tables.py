# ---- Syllable machines ----

CS_TYPES = {"unsigned char": "byte", "char": "sbyte", "short": "short", "unsigned short": "ushort", "int": "int"}


def machine(name):
    src = source(f"hb-ot-shaper-{name}-machine.hh")
    prefix = f"_{name}_syllable_machine_"
    out = []
    consts = re.findall(rf"#define {name}_syllable_machine_ex_(\w+) (\d+)u", src)
    out.append(f"    // {name.capitalize()} categories the machine reads.")
    for c, v in consts:
        out.append(f"    public const byte Ex{c} = {v};")
    enum = re.search(rf"enum {name}_syllable_type_t \{{(.*?)\}};", src, re.S).group(1)
    types = [t.strip() for t in enum.split(",") if t.strip()]
    out.append("")
    for i, t in enumerate(types):
        out.append(f"    public const int {''.join(w.capitalize() for w in t[len(name) + 1:].split('_'))} = {i};")
    out.append("")
    for m in re.finditer(rf"static const ([a-z ]+?) {prefix}(\w+)\[\] = \{{(.*?)\}};", src, re.S):
        values = numbers(m.group(3))
        out.append(f"    private static ReadOnlySpan<{CS_TYPES[m.group(1)]}> {m.group(2)} =>\n    [")
        for i in range(0, len(values), 24):
            out.append("        " + ", ".join(map(str, values[i:i + 24])) + ",")
        out.append("    ];\n")
    start = int(re.search(rf"static const int {name}_syllable_machine_start = (\d+);", src).group(1))
    out.append(f"    private const int Start = {start};\n")

    func = src[src.index(f"find_syllables_{name} (hb_buffer_t *buffer)"):]
    func = func[func.index("{") + 1:func.rindex("#undef found_syllable")]
    func = func[:func.rindex("}")]
    func = "\n".join(line for line in func.split("\n") if not line.startswith("#line"))
    func = re.sub(r"unsigned int p, pe, eof, ts, te, act( HB_UNUSED)?;", "int p, pe, eof, ts, te, act;", func)
    func = func.replace("hb_glyph_info_t *info = buffer->info;", "GlyphInfo[] info = buffer.Info;")
    func = func.replace("unsigned int syllable_serial = 1;", "int syllable_serial = 1;")
    func = func.replace("pe = eof = buffer->len;", "pe = eof = buffer.Len;")
    func = func.replace(f"cs = {name}_syllable_machine_start;", "cs = Start;")
    func = re.sub(r"int _slen;\s*int _trans;\s*const unsigned char \*_keys;\s*const (unsigned )?char \*_inds;",
                  "int _slen = 0;\n\tint _trans = 0;\n\tint _keys = 0;\n\tint _inds = 0;", func)
    func = func.replace(f"_keys = {prefix}trans_keys + (cs<<1);", "_keys = cs << 1;")
    func = func.replace(f"_inds = {prefix}indicies + {prefix}index_offsets[cs];", "_inds = index_offsets[cs];")
    func = func.replace(f"info[p].{name}_category()", "info[p].ShaperCategory")
    func = re.sub(r"_trans = _inds\[(.*?)\];", lambda m: "_trans = indicies[_inds + (" + m.group(1).replace("_keys[0]", "trans_keys[_keys]").replace("_keys[1]", "trans_keys[_keys + 1]") + ")];", func, flags=re.S)
    func = func.replace(prefix, "")
    func = re.sub(r"found_syllable \(" + name + r"_(\w+)\);",
                  lambda m: "FoundSyllable(info, ts, te, " + "".join(w.capitalize() for w in m.group(1).split("_")) + ", ref syllable_serial);", func)
    func = func.replace("buffer->scratch_flags |= HB_BUFFER_SCRATCH_FLAG_HAS_BROKEN_SYLLABLE;", "buffer.ScratchFlags |= LayoutBuffer.ScratchHasBrokenSyllable;")
    func = func.replace("_test_eof: {}", "_test_eof:")
    func = func.replace("\t", "    ")
    assert "->" not in func and "unsigned" not in func, func
    out.append("    /// <summary>Marks each syllable's glyphs with a serial and the syllable type, as HarfBuzz's find_syllables.</summary>")
    out.append("    public static void FindSyllables(LayoutBuffer buffer)\n    {")
    out.extend("    " + line if line.strip() else "" for line in func.strip("\n").split("\n"))
    out.append("        _ = act;\n        _ = ts;\n    }")
    return f"internal static class {name.capitalize()}Machine\n{{\n" + "\n".join(out) + "\n\n" + FOUND + "}\n"


FOUND = """    private static void FoundSyllable(GlyphInfo[] info, int ts, int te, int syllableType, ref int serial)
    {
        for (int i = ts; i < te; i++)
        {
            info[i].Syllable = (byte)((serial << 4) | syllableType);
        }

        serial++;
        if (serial == 16)
        {
            serial = 1;
        }
    }
"""

text = header("hb-ot-shaper-indic-machine.hh, hb-ot-shaper-khmer-machine.hh and hb-ot-shaper-myanmar-machine.hh")
text += "\n".join(machine(n) for n in ["indic", "khmer", "myanmar"])
write("SyllableMachines.g.cs", text)

# ---- Universal Shaping Engine ----
# The USE category table (hb-ot-shaper-use-table.hh, the speed-optimized packed table) and the USE syllable machine. Unlike the
# other machines, HarfBuzz runs the USE machine over the glyphs that are not CGJ (nor a ZWNJ before a mark), through an
# iterator; Egami runs it over a list of those glyphs' indices, so p, pe, ts and te index that list.

use_table = source("hb-ot-shaper-use-table.hh")
use_table = use_table[:use_table.index("#else")]
use_categories = {c: int(v) for c, v in re.findall(r"#define use_syllable_machine_ex_(\w+) (\d+)u", source("hb-ot-shaper-use-machine.hh"))}


def use_values(body):
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    return [use_categories[t] if t[0].isalpha() else int(t) for t in re.findall(r"[A-Za-z]\w*|\d+", body)]


use_u8 = use_values(array_body(use_table, "hb_use_u8"))
use_u16 = numbers(array_body(use_table, "hb_use_u16"))
assert len(use_u8) == int(re.search(r"hb_use_u8\[(\d+)\]", use_table).group(1))
assert len(use_u16) == int(re.search(r"hb_use_u16\[(\d+)\]", use_table).group(1))
assert "(a[i>>1]>>((i&1)<<2))&15" in use_table
lookup = re.search(r"static inline uint8_t hb_use_get_category \(unsigned u\)\s*\{.*?return (.*?);\s*\}", use_table, re.S).group(1)
lookup = re.sub(r"(\d+)u\b", r"\1", lookup)
lookup = lookup.replace("hb_use_b4(hb_use_u8,", "B4(").replace("hb_use_u8[", "U8[").replace("hb_use_u16[", "U16[")
lookup = lookup.replace("(uint8_t)", "(byte)").replace(": O", ": (byte)0")
assert "hb_" not in lookup and "uint" not in lookup, lookup

text = header("hb-ot-shaper-use-table.hh")
text += "internal static class UseTable\n{\n"
for cs_name, cs_type, values in [("U8", "byte", use_u8), ("U16", "ushort", use_u16)]:
    text += f"    private static ReadOnlySpan<{cs_type}> {cs_name} =>\n    [\n"
    for i in range(0, len(values), 24):
        text += "        " + ", ".join(map(str, values[i:i + 24])) + ",\n"
    text += "    ];\n\n"
text += "    private static int B4(int i) => (U8[i >> 1] >> ((i & 1) << 2)) & 15;\n\n"
text += "    /// <summary>A code point's Universal Shaping Engine category, as HarfBuzz's hb_use_get_category.</summary>\n"
text += f"    public static byte GetCategory(int u) => {lookup};\n}}\n"
write("UseTable.g.cs", text)


