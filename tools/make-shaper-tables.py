# hb-ot-shaper-indic-table.cc: each character's Indic, Khmer or Myanmar category and its Indic position, packed into a
# two-level table; the lookup is written out with the generated arrays, the categories resolved to the machines' values.

src = source("hb-ot-shaper-indic-table.cc")
machine_values = {}
for prefix, name in (("I", "indic"), ("K", "khmer"), ("M", "myanmar")):
    for c, v in re.findall(rf"#define {name}_syllable_machine_ex_(\w+) (\d+)u", source(f"hb-ot-shaper-{name}-machine.hh")):
        machine_values[f"{prefix}_Cat({c})"] = int(v)
ot = {}
for m in re.finditer(r"#define (OT_\w+) ([IKM]_Cat\(\w+\))", src):
    ot[m.group(1)] = machine_values[m.group(2)]
for m in re.finditer(r"static_assert \((OT_\w+) == ([IKM]_Cat\(\w+\))", src):
    assert ot[m.group(1)] == machine_values[m.group(2)]
short_cat = {m.group(1): ot[m.group(2)] for m in re.finditer(r"#define (_OT_\w+)\s+(OT_\w+)", src)}
positions = {m.group(1): int(m.group(2)) for m in re.finditer(r"(POS_\w+) = (\d+)", source("hb-ot-shaper-indic.hh"))}
short_pos = {m.group(1): positions[m.group(2)] for m in re.finditer(r"#define (_POS_\w+)\s+(POS_\w+)", src)}
values = [short_cat["_OT_" + s] | (short_pos["_POS_" + p] << 8)
          for s, p in re.findall(r"_\((\w+),(\w+)\)", array_body(src, "_hb_indic_values"))]
