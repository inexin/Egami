"""Generates the Unicode block table egami font info reports coverage with (2.7.8), from the Unicode Character Database.

Downloads Blocks.txt for the pinned Unicode version, the same version tools/make-unicode-tables.py uses, into
.cache/ucd/<version>/ (checked against its SHA-256; the file is not committed) and writes:
  src/Egami.Cli/Commands/UnicodeBlocks.g.cs   every block's first and last code point and name

The output depends only on Blocks.txt, so running the tool twice gives the same bytes.

Usage, from the repo root:
  python tools/make-unicode-blocks.py
"""
import hashlib
import os
import sys
import urllib.request

VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/Blocks.txt"
SHA256 = "c0edefaf1a19771e830a82735472716af6bf3c3975f6c2a23ffbe2580fbbcb15"
OUT = "src/Egami.Cli/Commands/UnicodeBlocks.g.cs"


def fetch():
    path = os.path.join(".cache", "ucd", VERSION, "Blocks.txt")
    if not os.path.exists(path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        print(f"Downloading {URL}")
        with urllib.request.urlopen(URL) as response:
            data = response.read()
        with open(path, "wb") as f:
            f.write(data)
    with open(path, "rb") as f:
        data = f.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"{path}: SHA-256 {digest} does not match the pinned {SHA256}; delete it and run again.")
    return data.decode("utf-8")


def main():
    blocks = []
    for line in fetch().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        span, name = (f.strip() for f in line.split(";", 1))
        first, last = (int(v, 16) for v in span.split(".."))
        blocks.append((first, last, name))
    blocks.sort()
    lines = [
        "// <auto-generated/>",
        f"// Generated by tools/make-unicode-blocks.py from the Unicode Character Database {VERSION} (Blocks.txt); do not edit.",
        "// Unicode data: Copyright (c) 1991-2025 Unicode, Inc. Unicode License v3; see THIRD-PARTY-NOTICES.md.",
        "",
        "namespace Egami.Cli.Commands;",
        "",
        f"/// <summary>The Unicode {VERSION} blocks, in code point order, for <c>egami font info</c>'s coverage.</summary>",
        "internal static class UnicodeBlocks",
        "{",
        "    /// <summary>Gets each block's first and last code point and name.</summary>",
        "    public static (int First, int Last, string Name)[] All { get; } =",
        "    [",
    ]
    for first, last, name in blocks:
        lines.append(f'        (0x{first:04X}, 0x{last:04X}, "{name}"),')
    lines += ["    ];", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT}: {len(blocks)} blocks")


if __name__ == "__main__":
    main()
