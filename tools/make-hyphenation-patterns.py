def source(name):
    path = f"{CACHE}/hyph-{name}.tex"
    if not os.path.exists(path):
        os.makedirs(CACHE, exist_ok=True)
        with urllib.request.urlopen(URL + f"hyph-{name}.tex") as response:
            open(path, "wb").write(response.read())
    data = open(path, "rb").read()
    if hashlib.sha256(data).hexdigest() != SHA256[name]:
        sys.exit(f"{path} does not match the pinned SHA-256.")
    return path, data.decode("utf-8")


def header(text):
    lines = []
    for line in text.splitlines():
        if not line.startswith("%") or line.startswith("% ===="):
            break
        lines.append(line[2:] if line.startswith("% ") else line[1:])
    return yaml.safe_load("\n".join(lines))


def licence(name, head, choice):
    """The chosen licence entry of a header: its name and text. Fails when the header no longer offers it."""
    entries = head["licence"] if isinstance(head["licence"], list) else [head["licence"]]
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        if choice == "text" and "name" not in entry and "text" in entry:
            return "permissive notice", entry["text"].strip()
        if entry.get("name") == choice:
            text = (entry.get("text") or "").strip()
            if not text and choice.startswith("MIT"):
                text = MIT_TEXT
            if not text:
                text = f"{choice}: {entry.get('url', '')}"
            return choice, text
    sys.exit(f"hyph-{name}.tex no longer offers the {choice} licence; check its header.")


def main():
    os.makedirs(OUT, exist_ok=True)
    jobs, notices = [], []
    for tag, name, choice in LANGUAGES:
        path, text = source(name)
        head = header(text)
        lic, lic_text = licence(name, head, choice)
        patterns, exceptions = path, None
        if "\\input hyph-no.tex" in text:
            patterns, _ = source("no")
            exceptions = path
            # The patterns come from hyph-no.tex: its notice applies too.
            no_head = header(source("no")[1])
            no_lic = licence("no", no_head, "text")
        copyright_line = str(head.get("copyright", "")).strip()
        title = str(head.get("title", "")).strip()
        jobs.append({
            "tag": tag,
            "patterns": patterns,
            "exceptions": exceptions,
            "output": f"{OUT}/{tag}.ehyp",
            "metadata": {
                "language": tag,
                "title": title,
                "copyright": copyright_line,
                "licence": lic,
                "source": f"hyph-utf8 {COMMIT[:12]} hyph-{name}.tex",
            },
        })
        shown = lic if "licen" in lic.lower() or lic.startswith("permissive") else f"{lic} licence"
        block = [f"### {tag}: {title}", "", f"From `hyph-{name}.tex`, under the {shown} it offers.", "", f"    {copyright_line}", ""]
        block += ["    " + line if line else "" for line in lic_text.splitlines()]
        if exceptions:
            block += ["", f"Its patterns are hyph-no.tex's:", "", f"    {str(no_head.get('copyright', '')).strip()}", ""]
            block += ["    " + line if line else "" for line in no_lic[1].splitlines()]
        notices.append("\n".join(block))

    job_path = f"{CACHE}/job.json"
    json.dump(jobs, open(job_path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    subprocess.run(["dotnet", "run", "tools/hyphenation/compile-ehyp.cs", "--", job_path], check=True)

    section = "\n\n".join([
        BEGIN,
        "## hyph-utf8 hyphenation patterns",
        "Egami.Fonts' built-in hyphenation dictionaries (`HyphenationDictionaries.BuiltIn`) are compiled from the hyph-utf8 "
        f"package's pattern files (github.com/hyphenation/tex-hyphen, commit {COMMIT}). Each is used under the permissive licence "
        "its header grants, chosen as named below where it offers several.",
        *notices,
        END,
    ])
    notices_text = open(NOTICES, encoding="utf-8").read()
    if BEGIN in notices_text:
        start = notices_text.index(BEGIN)
        end = notices_text.index(END) + len(END)
        notices_text = notices_text[:start] + section + notices_text[end:]
    else:
        notices_text = notices_text.rstrip("\n") + "\n\n" + section + "\n"
    open(NOTICES, "w", encoding="utf-8", newline="\n").write(notices_text)
    total = sum(os.path.getsize(f"{OUT}/{tag}.ehyp") for tag, _, _ in LANGUAGES)
    print(f"{len(LANGUAGES)} languages, {total} bytes")


main()
