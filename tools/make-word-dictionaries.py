"""Generates Egami.Fonts' built-in word dictionaries (src/Egami.Fonts/Layout/WordBreaking/Dictionaries/*.edict) and their
section of THIRD-PARTY-NOTICES.md (roadmap 2.8.5, Build Plan task 1).

The sources are ICU's word lists for Thai, Lao, Khmer and Myanmar (github.com/unicode-org/icu,
icu4c/source/data/brkitr/dictionaries) at a pinned release tag, each SHA-256 checked, downloaded into .cache/icu-dict/<tag>
with ICU's LICENSE. Thai and Khmer are under the Unicode License v3; the Lao list is BSD-2 (Brian Eugene Wilson, Robert
Martin Campbell) and the Myanmar list BSD-3 (LeRoy Benjamin Sharon), as their headers say. The tool drops comments, dedupes
and sorts the words, checks each list stays in its script's block (plus ZWNJ and ZWJ), compiles them with
tools/word-breaking/compile-edict.cs and writes the notices into THIRD-PARTY-NOTICES.md between the markers.

Never edit the .edict files by hand; rerun this tool. Needs the .NET 10 SDK.

Usage, from the repo root:
  python tools/make-word-dictionaries.py
"""
import hashlib
import json
import os
import subprocess
import sys
import urllib.request

TAG = "release-79.1"
URL = f"https://raw.githubusercontent.com/unicode-org/icu/{TAG}/"
DICTIONARIES = "icu4c/source/data/brkitr/dictionaries/"
CACHE = f".cache/icu-dict/{TAG}"
OUT = "src/Egami.Fonts/Layout/WordBreaking/Dictionaries"
NOTICES = "THIRD-PARTY-NOTICES.md"
BEGIN = "<!-- word dictionaries: generated by tools/make-word-dictionaries.py -->"
END = "<!-- end of word dictionaries -->"

# Output name, ICU file, script, and the code points the words may use: the script's block (Myanmar's runs to U+109F) and
# the zero width non-joiner and joiner, which a few Khmer and Myanmar words hold.
SCRIPTS = [
    ("th", "thaidict.txt", "Thai", range(0x0E00, 0x0E80)),
    ("lo", "laodict.txt", "Lao", range(0x0E80, 0x0F00)),
    ("km", "khmerdict.txt", "Khmer", range(0x1780, 0x1800)),
    ("my", "burmesedict.txt", "Myanmar", range(0x1000, 0x10A0)),
]
JOINERS = {0x200C, 0x200D}

SHA256 = {
    "LICENSE": "e09827667e0bb3c808b2a463548ba814a5e6249b67353234d70c8dfc2bcc417d",
    "thaidict.txt": "3166abde40c0f44ab91c28f5ce96d7d1472cb7882e1c0bda0a72f8f69dba4274",
    "laodict.txt": "3c876934a3fa81031d2333525eafaca6a7c9f842e3b98f18c38880420afb5d36",
    "khmerdict.txt": "87bee2d17cd5148aa36957eb05409eefc124de8ad519b81b789298ef3e60b5d9",
    "burmesedict.txt": "61d8abc3d9102b2f9bf0c9f44db0d7ab89b18172d8cd26832e4c83174bd8673b",
}


def source(name, path):
    local = f"{CACHE}/{name}"
    if not os.path.exists(local):
        os.makedirs(CACHE, exist_ok=True)
        with urllib.request.urlopen(URL + path) as response:
            open(local, "wb").write(response.read())
    data = open(local, "rb").read()
    if hashlib.sha256(data).hexdigest() != SHA256[name]:
        sys.exit(f"{local} does not match the pinned SHA-256.")
    return data.decode("utf-8-sig")


def words(text, script, allowed):
    """The list's words, deduped and sorted by UTF-16 code unit (all are in the BMP, so by code point)."""
    found = set()
    for line in text.splitlines():
        word = line.strip()
        if not word or word.startswith("#"):
            continue
        for c in word:
            if ord(c) not in allowed and ord(c) not in JOINERS:
                sys.exit(f"The {script} list has U+{ord(c):04X} in '{word}'; check the source.")
        found.add(word)
    return sorted(found)


def comment_block(text, first, last):
    """The header comment lines from the one containing `first` to the one containing `last`, without '#' and indentation."""
    lines = [line.strip().lstrip("#") for line in text.splitlines() if line.strip().startswith("#")]
    lines = [line[1:] if line.startswith((" ", "\t")) else line for line in lines]
    lines = [line.replace("\t", "  ").rstrip() for line in lines]
    start = next(i for i, line in enumerate(lines) if first in line)
    end = next(i for i in range(start, len(lines)) if last in lines[i])
    return "\n".join(lines[start:end + 1])


def unicode_license(text):
    """The Unicode License v3 at the top of ICU's LICENSE, up to its SPDX line."""
    head = text[:text.index("SPDX-License-Identifier: Unicode-3.0")]
    return head.strip()


def indent(text):
    return "\n".join("    " + line if line.strip() else "" for line in text.splitlines())


def main():
    os.makedirs(OUT, exist_ok=True)
    licence = source("LICENSE", "LICENSE")
    jobs, counts, texts = [], {}, {}
    for name, file, script, allowed in SCRIPTS:
        text = source(file, DICTIONARIES + file)
        texts[file] = text
        listed = words(text, script, allowed)
        counts[name] = len(listed)
        words_path = f"{CACHE}/{name}.words.txt"
        open(words_path, "w", encoding="utf-8", newline="\n").write("\n".join(listed) + "\n")
        jobs.append({"words": words_path, "output": f"{OUT}/{name}.edict"})

    job_path = f"{CACHE}/job.json"
    json.dump(jobs, open(job_path, "w", encoding="utf-8"), indent=1)
    subprocess.run(["dotnet", "run", "tools/word-breaking/compile-edict.cs", "--", job_path], check=True)

    lao = comment_block(texts["laodict.txt"], "Copyright (C) 2013 Brian Eugene Wilson", "SOFTWARE, EVEN IF ADVISED")
    myanmar = comment_block(texts["burmesedict.txt"], "Copyright (c) 2013, LeRoy Benjamin Sharon", "SOFTWARE, EVEN IF ADVISED")
    thai_copyright = comment_block(texts["thaidict.txt"], "Copyright (C) 2016 and later", "Apple Inc., and others")
    khmer_copyright = comment_block(texts["khmerdict.txt"], "Copyright (C) 2016 and later", "and others. All Rights Reserved")
    section = "\n\n".join([
        BEGIN,
        "## ICU word break dictionaries",
        "Egami.Fonts' built-in word dictionaries (`WordDictionaries.BuiltIn`) are compiled from ICU's word lists "
        f"(github.com/unicode-org/icu, tag {TAG}, `{DICTIONARIES}`): `thaidict.txt`, `laodict.txt`, `khmerdict.txt` and "
        "`burmesedict.txt`. Only the words are kept, as a word graph; the lists' comments are dropped.",
        "### Thai and Khmer (`thaidict.txt`, `khmerdict.txt`): Unicode License v3",
        "The Thai list's header:",
        indent(thai_copyright),
        "The Khmer list's header:",
        indent(khmer_copyright),
        "Both are distributed under ICU's licence:",
        indent(unicode_license(licence)),
        "### Lao (`laodict.txt`): BSD 2-clause licence",
        "The Lao word list comes from github.com/rober42539/lao-dictionary through ICU, under this notice from its header:",
        indent(lao),
        "### Myanmar (`burmesedict.txt`): BSD 3-clause licence",
        "The Burmese word list comes from github.com/kanyawtech/myanmar-karen-word-lists through ICU, under this notice from its "
        "header:",
        indent(myanmar),
        END,
    ])
    notices_text = open(NOTICES, encoding="utf-8").read()
    if BEGIN in notices_text:
        start = notices_text.index(BEGIN)
        end = notices_text.index(END) + len(END)
        notices_text = notices_text[:start] + section + notices_text[end:]
    else:
        notices_text = notices_text.rstrip("\n") + "\n\n" + section + "\n"
    open(NOTICES, "w", encoding="utf-8", newline="\n").write(notices_text)
    for name, _, script, _ in SCRIPTS:
        print(f"{script}: {counts[name]} words, {os.path.getsize(f'{OUT}/{name}.edict')} bytes")


main()
