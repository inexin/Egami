"""Generates src/Egami.Fonts/Shaping/LanguageTags.g.cs: BCP 47 language tags to OpenType language system tags (2.8.1 question 11).

HarfBuzz generates its table from the OpenType language system tag registry and the IANA language subtag registry, with the
corrections its tests rely on; Egami translates that table (MIT) so a language picks the same language system as hb-shape. The
tool reads hb-ot-tag-table.hh from HarfBuzz 14.5.1's release tarball (SHA-256 checked, downloaded into .cache/harfbuzz by
tools/make-shaping-references.py) and writes the data arrays and the multi-subtag rules as C#.

Usage, from the repo root:
  python tools/make-language-tags.py
"""
import hashlib
import io
import re
import sys
import tarfile

VERSION = "14.5.1"
TARBALL = f".cache/shaping/github.com_harfbuzz_harfbuzz_releases_download_{VERSION}_harfbuzz-{VERSION}.tar.xz"
SHA256 = "7e2fa4e8c7c98e8d8140671f5772542afaaa6acccfbd746506886b6d85f7f8d6"
OUT = "src/Egami.Fonts/Shaping/LanguageTags.g.cs"

data = open(TARBALL, "rb").read()
if hashlib.sha256(data).hexdigest() != SHA256:
    sys.exit(f"{TARBALL} does not match the pinned SHA-256; run tools/make-shaping-references.py first.")
source = tarfile.open(fileobj=io.BytesIO(data)).extractfile(f"harfbuzz-{VERSION}/src/hb-ot-tag-table.hh").read().decode("utf-8")


def tag(match):
    chars = [c.replace("\\'", "'") for c in re.findall(r"'(\\'|.)'", match)]
    return '"' + "".join(chars) + '"'


def tags_in(text):
    return [tag(m) for m in re.findall(r"HB_TAG\(([^)]*)\)", text)]


def array(name):
    start = source.index(f"{name}[] = {{")
    end = source.index("};", start)
    return source[start:end]


lang2 = re.findall(r"\{HB_TAG\(([^)]*)\),\s*HB_TAG\(([^)]*)\)\}", array("ot_languages2"))
lang3 = re.findall(r"\{HB_TAG\(([^)]*)\),\s*HB_TAG\(([^)]*)\)\}", array("ot_languages3"))
blocked = re.findall(r"HB_TAG\(([^)]*)\)", array("ot_languages3_blocked"))
multi_values = re.findall(r"HB_TAG\(([^)]*)\)", array("ot_languages3_multi_values"))
multi = re.findall(r"\{HB_TAG\(([^)]*)\),\s*(\d+),\s*(\d+)\}", array("ot_languages3_multi"))

# The multi-subtag rules: hb_ot_tags_from_complex_language, translated statement by statement.
start = source.index("hb_ot_tags_from_complex_language (")
body_start = source.index("{", start)
end = source.index("\n}\n", body_start)
body = source[body_start + 1:end]
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
body = re.sub(r"unsigned int i;\s*hb_tag_t possible_tags\[\] = \{(.*?)\};\s*for \(i = 0; i < \d+ && i < \*count; i\+\+\)\s*tags\[i\] = possible_tags\[i\];\s*\*count = i;",
              lambda m: "tags.AddRange([" + ", ".join(f"T({t})" for t in tags_in(m.group(1))) + "]);", body, flags=re.S)
body = re.sub(r"tags\[0\] = HB_TAG\(([^)]*)\);\s*\*count = 1;", lambda m: f"tags.Add(T({tag(m.group(1))}));", body)
body = body.replace("if (limit - lang_str >= 7)", "if (limit >= 7)")
body = body.replace("const char *p = strchr (lang_str, '-');", "int p = s.IndexOf('-');")
body = body.replace("if (!p || p >= limit || limit - p < 5) goto out;", "if (p < 0 || p >= limit || limit - p < 5) goto out;")
body = re.sub(r"subtag_matches \(p, limit, (\"[^\"]*\"), \d+\)", r"SubtagMatches(s, p, limit, \1)", body)
body = re.sub(r"subtag_matches \(lang_str, limit, (\"[^\"]*\"), \d+\)", r"SubtagMatches(s, 0, limit, \1)", body)
body = re.sub(r"lang_matches \(&lang_str\[1\], limit, (\"[^\"]*\"), \d+\)", r"LangMatches(s, 1, limit, \1)", body)
body = re.sub(r"0 == strcmp \(&lang_str\[1\], (\"[^\"]*\")\)", r"Rest(s, 1) == \1", body)
body = re.sub(r"0 == strncmp \(&lang_str\[1\], (\"[^\"]*\"), \d+\)", r"Starts(s, 1, \1)", body)
body = body.replace("goto out;", "goto Out;").replace("out:", "Out:")
body = body.replace("switch (lang_str[0])", "switch (s.Length > 0 ? s[0] : '\\0')")
for forbidden in ("HB_TAG", "lang_str", "*count", "strcmp", "strncmp", "possible_tags"):
    if forbidden in body:
        line = next(l for l in body.splitlines() if forbidden in l)
        sys.exit(f"Untranslated construct {forbidden!r}: {line.strip()}")

lines = [
    "// <auto-generated/>",
    f"// Generated by tools/make-language-tags.py from HarfBuzz {VERSION}'s hb-ot-tag-table.hh (MIT); see THIRD-PARTY-NOTICES.md.",
    "// Do not edit.",
    "#pragma warning disable",
    "",
    "namespace Egami.Fonts.Shaping;",
    "",
    "internal static partial class LanguageTags",
    "{",
    "    /// <summary>Two-letter languages and their OpenType tags, sorted by language; a language may have several.</summary>",
    "    private static readonly (string Language, string Tag)[] s_languages2 =",
    "    [",
]
lines += [f"        ({tag(a).replace(' ', '')}, {tag(b)})," for a, b in lang2]
lines += ["    ];", "", "    /// <summary>Three-letter languages with one OpenType tag, sorted.</summary>",
          "    private static readonly (string Language, string Tag)[] s_languages3 =", "    ["]
lines += [f"        ({tag(a).replace(' ', '')}, {tag(b)})," for a, b in lang3]
lines += ["    ];", "", "    /// <summary>Three-letter languages that are not the OpenType tag of the same letters.</summary>",
          "    private static readonly string[] s_blocked =", "    ["]
lines += [f"        {tag(a).replace(' ', '')}," for a in blocked]
lines += ["    ];", "", "    /// <summary>Three-letter languages with several OpenType tags: offset and count into s_multiValues.</summary>",
          "    private static readonly (string Language, int Offset, int Count)[] s_languages3Multi =", "    ["]
lines += [f"        ({tag(a).replace(' ', '')}, {o}, {c})," for a, o, c in multi]
lines += ["    ];", "", "    private static readonly string[] s_multiValues =", "    ["]
lines += [f"        {tag(a)}," for a in multi_values]
lines += ["    ];", "",
          "    /// <summary>The rules for language tags with several subtags, such as zh-Hant-HK or el-polyton.</summary>",
          "    private static bool FromComplexLanguage(string s, int limit, List<uint> tags)",
          "    {"]
for line in body.splitlines():
    if line.strip():
        lines.append("    " + line.replace("\t", "    ").rstrip())
lines += ["    }", "}", ""]
text = "\n".join(lines)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(text)
print(f"{len(lang2)} two-letter, {len(lang3)} three-letter, {len(multi)} multi, {len(blocked)} blocked")
