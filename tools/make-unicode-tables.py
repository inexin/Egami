"""Generates Egami.Fonts' Unicode tables from the Unicode Character Database (2.8.1 question 4).

Downloads UCD.zip for the pinned Unicode version into .cache/ucd/<version>/ (checked against its SHA-256; the UCD files are not
committed) and writes:
  src/Egami.Fonts/Unicode/UnicodeTables.g.cs   per-code-point properties as a two-stage lookup into a table of property records,
                                                 script extensions, mirroring, brackets and canonical (de)compositions
  src/Egami.Fonts/Unicode/UnicodeEnums.g.cs    the property value enums
  src/Egami.Fonts/Unicode/Script.g.cs          one Script member per Unicode script, with its ISO 15924 code and OpenType tags
  tests/reference/unicode/*.txt.gz             the expected values per code point and Unicode's conformance test files
                                                 (bidi, grapheme, word and, from 2.8.2, line break)

The output depends only on the UCD files, so running the tool twice gives the same bytes.

Usage, from the repo root:
  python tools/make-unicode-tables.py
"""
