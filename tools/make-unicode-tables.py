def fetch():
    path = os.path.join(".cache", "ucd", VERSION, "UCD.zip")
    if not os.path.exists(path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        print(f"Downloading {UCD_URL}")
        with urllib.request.urlopen(UCD_URL) as response:
            data = response.read()
        with open(path, "wb") as f:
            f.write(data)
    with open(path, "rb") as f:
        data = f.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != UCD_SHA256:
        sys.exit(f"{path}: SHA-256 {digest} does not match the pinned {UCD_SHA256}; delete it and run again.")
    return zipfile.ZipFile(io.BytesIO(data))


UCD = fetch()


def read(name):
    return UCD.read(name).decode("utf-8")


def rows(name):
    """Yields (first, last, fields) for every data line."""
    for line in read(name).splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(";")]
        first, _, last = fields[0].partition("..")
        yield int(first, 16), int(last or first, 16), fields[1:]


def missing(name):
    """Yields (first, last, value) for every @missing line, in file order."""
    for line in read(name).splitlines():
        m = re.match(r"#\s*@missing:\s*([0-9A-F]+)\.\.([0-9A-F]+)\s*;\s*(.+)$", line)
        if m:
            yield int(m.group(1), 16), int(m.group(2), 16), [f.strip() for f in m.group(3).split(";")]


# Property value aliases: property -> any alias -> (short, long).
ALIASES = {}
for line in read("PropertyValueAliases.txt").splitlines():
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    fields = [f.strip() for f in line.split(";")]
    prop = fields[0]
    if prop == "ccc":
        short, long = fields[2], fields[3]
        names = fields[1:]
    else:
        short, long = fields[1], fields[2]
        names = fields[1:]
    table = ALIASES.setdefault(prop, {})
    for n in names:
        table[n] = (short, long)


def canonical(prop, value):
    return ALIASES[prop][value][0] if prop in ALIASES and value in ALIASES[prop] else value


def enumerated(name, prop, field=0, default=None, use_missing=True):
    """A per-code-point list of a property's short values, @missing defaults applied first."""
    values = [default] * MAX
    for first, last, v in missing(name) if use_missing else []:
        if prop is not None and len(v) == 2:
            if v[0] != prop:
                continue
            v = v[1:]
        values[first:last + 1] = [canonical(prop, v[0])] * (last - first + 1)
    for first, last, fields in rows(name):
        if prop is not None and len(fields) > field + 1 and fields[field] == prop:
            value = fields[field + 1]
        elif prop is not None and name == "DerivedCoreProperties.txt":
            continue
        else:
            value = fields[field]
        values[first:last + 1] = [canonical(prop, value)] * (last - first + 1)
    return values


def binary(name, prop):
    flags = [False] * MAX
    for first, last, fields in rows(name):
        if fields[0] == prop:
            flags[first:last + 1] = [True] * (last - first + 1)
    return flags


