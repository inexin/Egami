def span(type_name, name, values, per_line=24, doc=None):
    lines = []
    if doc:
        lines.append(f"    /// <summary>{doc}</summary>")
    lines.append(f"    internal static ReadOnlySpan<{type_name}> {name} =>")
    lines.append("    [")
    for i in range(0, len(values), per_line):
        lines.append("        " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    lines.append("    ];")
    return "\n".join(lines)


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


