def gz(path, text):
    # A fixed mtime and no file name keep the bytes the same from run to run.
    with open(path, "wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=9) as f:
            f.write(text.encode("utf-8"))


