def pva_values(prop):
    seen = {}
    for alias, (short, long) in ALIASES[prop].items():
        seen[short] = long
    return seen


def file_values(values, default):
    return sorted(set(values) - {default})


def enum_spec(cs_name, prop, default, values, public, doc, member_doc):
    longs = pva_values(prop) if prop else {}
    order = [default] + [v for v in sorted(set(values) | (set(longs) if prop else set())) if v != default]
    members = []
    for v in order:
        long = longs.get(v, v)
        if prop and v not in set(values) and v != default:
            # Values the property defines but no code point has (such as the old emoji break classes) are left out.
            continue
        members.append((v, pascal(long), long))
    return dict(name=cs_name, members=members, public=public, doc=doc, member_doc=member_doc)


