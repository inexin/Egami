# KTX 1.1 files from toktx: name, toktx arguments, inputs, the input of the last surface for its reference.
TOKTX = [
    ("rgba8", [], ["rgba.png"], None),
    ("rgba8-bottom-left", ["--lower_left_maps_to_s0t0"], ["rgba.png"], None),
    ("rgb8-mips", ["--genmipmap"], ["rgb.png"], None),
    ("r8", ["--assign_oetf", "linear"], ["gray.png"], None),
    ("cube", ["--cubemap"], FACES, ("s5", "face5.png")),
    ("array", ["--layers", "3"], SLICES, ("s2", "slice2.png")),
]

# Formats Egami refuses for now: name, ktx create arguments.
UNSUPPORTED = [
    ("unsupported-uastc", ["--format", "R8G8B8A8_SRGB", "--encode", "uastc"]),
    ("unsupported-etc1s", ["--format", "R8G8B8A8_SRGB", "--encode", "basis-lz"]),
    ("unsupported-astc", ["--format", "ASTC_4x4_SRGB_BLOCK"]),
]

# Files small enough to be fuzz seeds.
SEED_FILES = ["rgba8-bottom-left.ktx", "r8.ktx", "cube.ktx", "rgb8-mips.ktx", "rgba8-zstd.ktx2", "rgb8-zlib.ktx2", "rg8-swizzle.ktx2",
              "rgba8-volume.ktx2", "rgba8-bottom-left.ktx2", "raw-bc7-zstd.ktx2", "raw-bc1-rgb.ktx2", "raw-rgba16f.ktx2"]


def validate(path):
    """Returns `ktx validate`'s verdict: "valid", or its messages."""
    result = subprocess.run(["ktx", "validate", path], capture_output=True)
    text = (result.stdout.decode() + result.stderr.decode()).strip()
    return "valid" if result.returncode == 0 else text


def entry(tool, arguments, sources, path):
    with open(path, "rb") as f:
        data = f.read()
    verdict = validate(path) if path.endswith(".ktx2") else "not checked (ktx validate reads KTX 2 only)"
    return {"tool": tool, "arguments": arguments, "inputs": sources, "validate": verdict, "sha256": hashlib.sha256(data).hexdigest()}


def committed():
    inputs()
    for folder in (CORPUS, TARGET, *SEEDS.values()):
        shutil.rmtree(folder, ignore_errors=True)
        os.makedirs(folder)
    manifest = {}
    for name, arguments, sources, extras in CREATED:
        out = f"{CORPUS}/{name}.ktx2"
        run("ktx", "create", *arguments, *[f"{WORK}/{s}" for s in sources], out)
        manifest[f"{name}.ktx2"] = entry("ktx create", arguments, sources, out)
        run("ktx", "extract", out, f"{TARGET}/{name}.png")
        for suffix, extract in extras:
            run("ktx", "extract", *extract, out, f"{TARGET}/{name}-{suffix}.png")

    generator = Generator(1999)
    width, height = 37, 23
    for name, vk, unit, extra in RAW:
        count = ((width + 3) // 4) * ((height + 3) // 4) * unit if unit > 0 else width * height * -unit
        data = generator.bytes(count)
        if vk.endswith("SFLOAT"):
            data = finite(vk, data)
        raw = f"{WORK}/{name}.bin"
        with open(raw, "wb") as f:
            f.write(data)
        out = f"{CORPUS}/{name}.ktx2"
        arguments = ["--raw", "--format", vk, "--width", str(width), "--height", str(height), *extra]
        run("ktx", "create", *arguments, raw, out)
        manifest[f"{name}.ktx2"] = entry("ktx create", arguments, [f"{name}.bin"], out)
        write_gz(f"{TARGET}/{name}.bin.gz", data)

    for name, arguments, sources, last in TOKTX:
        out = f"{CORPUS}/{name}.ktx"
        run("toktx", *arguments, out, *[f"{WORK}/{s}" for s in sources])
        manifest[f"{name}.ktx"] = entry("toktx", arguments, sources, out)
        shutil.copy(f"{WORK}/{sources[0]}", f"{TARGET}/{name}-ktx1.png")
        if last:
            shutil.copy(f"{WORK}/{last[1]}", f"{TARGET}/{name}-ktx1-{last[0]}.png")

    for name, arguments in UNSUPPORTED:
        out = f"{CORPUS}/{name}.ktx2"
        run("ktx", "create", *arguments, f"{WORK}/rgba.png", out)
        manifest[f"{name}.ktx2"] = entry("ktx create", arguments, ["rgba.png"], out)

    for file in SEED_FILES:
        shutil.copy(f"{CORPUS}/{file}", f"{SEEDS['ktx2' if file.endswith('.ktx2') else 'ktx']}/{file}")

    manifest = {"ktx-software": run("ktx", "--version").strip(), "files": manifest}
    invalid = [name for name, e in manifest["files"].items() if e["validate"] not in ("valid",) and name.endswith(".ktx2")]
    if invalid:
        raise RuntimeError(f"ktx validate rejects {invalid}")
    with open(f"{TARGET}/manifest.json", "w", newline="\n") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
        f.write("\n")


def finite(vk, data):
    """Clears the exponent's top bit of each half or float, so raw float data holds no infinities or NaNs."""
    out = bytearray(data)
    step = 2 if "16" in vk else 4
    for i in range(step - 1, len(out), step):
        out[i] &= 0xBF
    return bytes(out)


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--inside":
        os.makedirs(WORK, exist_ok=True)
        committed()
        return
    repo = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    if subprocess.run(["docker", "image", "inspect", IMAGE], capture_output=True).returncode != 0:
        subprocess.run(["docker", "build", "-t", IMAGE, "-"], input=DOCKERFILE.encode(), check=True)
    subprocess.run(["docker", "run", "--rm", "-v", f"{repo}:/work", "-w", "/work", IMAGE, "python3", "tools/make-ktx-references.py", "--inside"],
                   check=True)


if __name__ == "__main__":
    main()
