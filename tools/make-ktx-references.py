    ("rg8-swizzle", ["--format", "R8G8_UNORM", "--assign-tf", "linear", "--swizzle", "rrrg"], ["gray-alpha.png"], []),
    ("r8-swizzle", ["--format", "R8_UNORM", "--assign-tf", "linear", "--swizzle", "rrr1"], ["gray.png"], []),
    ("r8-srgb", ["--format", "R8_SRGB"], ["gray.png"], []),
    ("rgba8-p3", ["--format", "R8G8B8A8_SRGB", "--assign-primaries", "displayp3"], ["rgba.png"], []),
    ("rgba8-bottom-left", ["--format", "R8G8B8A8_SRGB", "--convert-texcoord-origin", "bottom-left"], ["rgba.png"], []),
    ("rgba8-cube", ["--format", "R8G8B8A8_SRGB", "--cubemap"], FACES, [("s5", ["--face", "5"])]),
    ("rgba8-array", ["--format", "R8G8B8A8_SRGB", "--layers", "3"], SLICES, [("s2", ["--layer", "2"])]),
