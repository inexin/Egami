"""Builds the KTX and KTX 2 test corpus with KTX-Software 4.4.2 (Apache-2.0) in Docker: `ktx create` and `toktx` make the files,
`ktx validate` checks every KTX 2 file, and `ktx extract` writes the reference decodes.

Inputs, all made here with Pillow from tests/images/ops/duck.png (public domain): 37 by 23 crops as RGBA, RGB, gray and
gray-alpha PNG (odd sizes, so the last row and column of 4 × 4 blocks are partial), 16 by 16 crops for the cube faces, 20 by 12
crops for array layers and depth slices, and a 37 by 1 row for a 1D texture. Block and uncompressed formats Pillow cannot
make go in as raw data: bytes from a fixed generator, which every BC format decodes (BC6H and BC7 meet every mode).

Committed corpus (tests/images/ktx; references in tests/reference/ktx):
  <name>.ktx2        made by `ktx create` with the arguments in manifest.json: sRGB and linear RGBA8, RGB8, RG8 and R8,
                     Zstandard and zlib supercompression, generated mips, a swizzle, a bottom-left origin (stored bottom-up,
                     KTXorientation ru), a cube map, an array, a volume and a 1D texture
  raw-<format>.ktx2  made by `ktx create --raw` from generated bytes: BC1 to BC7, BC6H signed and unsigned, BGRA8, packed
                     16- and 32-bit formats and float formats; the tests compare each with a DDS file of the same bytes
  <name>.ktx         KTX 1.1 files made by toktx: RGBA8, a bottom-left origin, RGB8 with mips, R8, a cube map and an array
  unsupported-*.ktx2 UASTC, Basis Universal ETC1S and ASTC files, which Egami refuses with a clear message for now
  manifest.json      per file: the tool and arguments, its inputs, `ktx validate`'s verdict and the SHA-256

  tests/reference/ktx/<name>.png       `ktx extract` of mip 0 of the first surface, as stored: R8 and R8G8 come out red and
                                       red-green, without the swizzle, and a bottom-left texture bottom-up
  tests/reference/ktx/<name>-ktx1.png  the input PNG of a KTX 1 file
  tests/reference/ktx/<name>-<x>.png   the same of another image: -l1 mip 1, -s<n> the last surface
  tests/reference/ktx/<raw>.bin.gz     the raw bytes a raw-*.ktx2 file was made from

Fuzz seeds: the smallest files are copied to tests/images/fuzz/ktx-seeds (KTX 1) and ktx2-seeds (KTX 2).

Usage, from the repo root with Docker running:
  python tools/make-ktx-references.py
The script builds the image egami-ktx:4.4.2 (ubuntu:24.04, Python, Pillow and the KTX-Software release .deb) the first time.
"""
import gzip
import hashlib
import json
import os
import shutil
import subprocess
import sys

VERSION = "4.4.2"
IMAGE = f"egami-ktx:{VERSION}"
DOCKERFILE = f"""FROM ubuntu:24.04
RUN apt-get update -qq && apt-get install -y -qq curl ca-certificates python3 python3-pil > /dev/null \\
 && curl -sL -o /tmp/ktx.deb https://github.com/KhronosGroup/KTX-Software/releases/download/v{VERSION}/KTX-Software-{VERSION}-Linux-x86_64.deb \\
 && apt-get install -y -qq /tmp/ktx.deb > /dev/null && rm /tmp/ktx.deb
"""
CORPUS = "tests/images/ktx"
TARGET = "tests/reference/ktx"
SEEDS = {"ktx": "tests/images/fuzz/ktx-seeds", "ktx2": "tests/images/fuzz/ktx2-seeds"}
WORK = "/tmp/ktxwork"


class Generator:
    """A 64-bit linear congruential generator (Knuth's MMIX constants), so the raw inputs are the same on every run."""

    def __init__(self, seed):
        self.state = seed

    def next(self):
        self.state = (self.state * 6364136223846793005 + 1442695040888963407) & 0xFFFFFFFFFFFFFFFF
        return self.state >> 33

    def bytes(self, count):
        return bytes(self.next() & 255 for _ in range(count))


def run(*args):
    result = subprocess.run(list(map(str, args)), capture_output=True)
    if result.returncode != 0:
        raise subprocess.CalledProcessError(result.returncode, args, result.stdout, result.stderr)
    return result.stdout.decode() + result.stderr.decode()


def write_gz(path, data):
    # No name and a zero time in the header, so regenerating gives identical files.
    with open(path, "wb") as raw, gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as f:
        f.write(data)


def inputs():
    """Writes the PNG inputs to WORK and returns their names."""
    from PIL import Image
    with Image.open("tests/images/ops/duck.png") as duck:
        rgba = duck.convert("RGBA")
        box = (300, 200, 337, 223)
        rgba.crop(box).save(f"{WORK}/rgba.png")
        rgba.convert("RGB").crop(box).save(f"{WORK}/rgb.png")
        rgba.convert("L").crop(box).save(f"{WORK}/gray.png")
        rgba.convert("LA").crop(box).save(f"{WORK}/gray-alpha.png")
        rgba.crop((300, 210, 337, 211)).save(f"{WORK}/row.png")
        for i in range(6):
            rgba.crop((200 + 16 * i, 180, 216 + 16 * i, 196)).save(f"{WORK}/face{i}.png")
        for i in range(3):
            rgba.crop((240 + 20 * i, 230, 260 + 20 * i, 242)).save(f"{WORK}/slice{i}.png")


FACES = [f"face{i}.png" for i in range(6)]
SLICES = [f"slice{i}.png" for i in range(3)]

