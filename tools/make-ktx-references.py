class Generator:
    """A 64-bit linear congruential generator (Knuth's MMIX constants), so the raw inputs are the same on every run."""

    def __init__(self, seed):
        self.state = seed

    def next(self):
        self.state = (self.state * 6364136223846793005 + 1442695040888963407) & 0xFFFFFFFFFFFFFFFF
        return self.state >> 33

    def bytes(self, count):
        return bytes(self.next() & 255 for _ in range(count))


def run(*args):
    result = subprocess.run(list(map(str, args)), capture_output=True)
    if result.returncode != 0:
        raise subprocess.CalledProcessError(result.returncode, args, result.stdout, result.stderr)
    return result.stdout.decode() + result.stderr.decode()


def write_gz(path, data):
    # No name and a zero time in the header, so regenerating gives identical files.
    with open(path, "wb") as raw, gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as f:
        f.write(data)


