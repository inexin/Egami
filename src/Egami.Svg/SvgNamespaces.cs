namespace Egami.Svg;

/// <summary>The XML namespaces SVG files use.</summary>
/// <example>
/// <code language="csharp" source="../../tests/Egami.DocSamples/Svg.cs" region="edit"/>
/// </example>
public static class SvgNamespaces
{
    /// <summary>The SVG namespace, <c>http://www.w3.org/2000/svg</c>.</summary>
    public const string Svg = "http://www.w3.org/2000/svg";

    /// <summary>The XLink namespace of SVG 1.1's <c>xlink:href</c>, <c>http://www.w3.org/1999/xlink</c>.</summary>
    public const string XLink = "http://www.w3.org/1999/xlink";

    /// <summary>The XML namespace of <c>xml:space</c> and <c>xml:lang</c>, <c>http://www.w3.org/XML/1998/namespace</c>.</summary>
    public const string Xml = "http://www.w3.org/XML/1998/namespace";

    /// <summary>The namespace of <c>xmlns</c> declarations, <c>http://www.w3.org/2000/xmlns/</c>.</summary>
    public const string Xmlns = "http://www.w3.org/2000/xmlns/";
}
