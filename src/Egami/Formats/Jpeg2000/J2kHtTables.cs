    /// <summary>
    /// The lookup tables, indexed by <c>(context &lt;&lt; 7) | bits</c>: 1,024 entries for initial line-pair quads, then 1,024 for
    /// the others. Each entry holds the codeword length (bits 0-2), the unsigned residual offset (bit 3), the significance
    /// pattern rho (bits 4-7), the EMB known-1 pattern (bits 8-11) and the EMB known bit pattern (bits 12-15).
    /// </summary>
    internal static readonly ushort[] Vlc = Build(); // after the tables it reads: static fields initialize in order

    /// <summary>Gets the two code tables as Annex C lists them, for the tests that check they form complete prefix codes.</summary>
    internal static ReadOnlySpan<uint> Entries(int table) => table == 0 ? Table0 : Table1;

    private static ushort[] Build()
    {
        ushort[] lookup = new ushort[2 * 8 * 128];
        for (int table = 0; table < 2; table++)
        {
            foreach (uint e in Entries(table))
            {
                int context = (int)(e >> 23);
                int rho = (int)(e >> 19) & 0xF;
                int offset = (int)(e >> 18) & 1;
                int known = (int)(e >> 14) & 0xF;
                int ones = (int)(e >> 10) & 0xF;
                int codeword = (int)(e >> 3) & 0x7F;
                int length = (int)(e & 7);
                ushort value = (ushort)(length | (offset << 3) | (rho << 4) | (ones << 8) | (known << 12));

                // Every 7-bit continuation of the codeword decodes to it.
                for (int rest = 0; rest < 1 << (7 - length); rest++)
                {
                    lookup[(table << 10) | (context << 7) | codeword | (rest << length)] = value;
                }
            }
        }

        return lookup;
    }
